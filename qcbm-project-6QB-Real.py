axes[2].set_title("Ideal QCBM (Statevector)")
axes[2].set_xlabel("\(p_T\) (GeV/c)")

# Plot 4: Real QPU QCBM
im3 = axes[3].imshow(noisy_qcbm_grid.T, origin='lower', extent=extent, aspect='auto', cmap=cmap)
#axes[3].set_title(f"Noisy QCBM ({type(real_backend).backend_name})")
axes[3].set_title(f"Real QPU ({real_backend.name})")
